package io.vidocq.noether.jpa.jta;

import java.sql.Array;
import java.sql.Blob;
import java.sql.CallableStatement;
import java.sql.Clob;
import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.NClob;
import java.sql.PreparedStatement;
import java.sql.SQLClientInfoException;
import java.sql.SQLException;
import java.sql.SQLWarning;
import java.sql.SQLXML;
import java.sql.Savepoint;
import java.sql.Statement;
import java.sql.Struct;
import java.util.Map;
import java.util.Properties;
import java.util.concurrent.Executor;

/**
 * A handle on the connection a transaction enlisted, as a container's data source hands it out: closing the handle
 * hands it back and leaves the connection open, and only the transaction manager completes the connection.
 */
final class ConnectionHandle implements Connection {
    private final Connection physical;
    private volatile boolean closed;

    ConnectionHandle(Connection physical) {
        this.physical = physical;
    }

    private Connection open() throws SQLException {
        if (closed) throw new SQLException("The connection handle is closed");
        return physical;
    }

    private static SQLException managed(String operation) {
        return new SQLException("The connection takes part in a JTA transaction: the transaction manager does the "
            + operation);
    }

    @Override public void close() { closed = true; }
    @Override public boolean isClosed() { return closed; }
    @Override public boolean isValid(int timeout) throws SQLException { return !closed && physical.isValid(timeout); }

    @Override public void commit() throws SQLException { open(); throw managed("commit"); }
    @Override public void rollback() throws SQLException { open(); throw managed("rollback"); }
    @Override public void rollback(Savepoint savepoint) throws SQLException { open().rollback(savepoint); }
    @Override public void setAutoCommit(boolean autoCommit) throws SQLException { if (autoCommit != open().getAutoCommit()) throw managed("commit"); }
    @Override public boolean getAutoCommit() throws SQLException { return open().getAutoCommit(); }

    @Override public Statement createStatement() throws SQLException { return open().createStatement(); }
    @Override public Statement createStatement(int type, int concurrency) throws SQLException { return open().createStatement(type, concurrency); }
    @Override public Statement createStatement(int type, int concurrency, int holdability) throws SQLException { return open().createStatement(type, concurrency, holdability); }
    @Override public PreparedStatement prepareStatement(String sql) throws SQLException { return open().prepareStatement(sql); }
    @Override public PreparedStatement prepareStatement(String sql, int type, int concurrency) throws SQLException { return open().prepareStatement(sql, type, concurrency); }
    @Override public PreparedStatement prepareStatement(String sql, int type, int concurrency, int holdability) throws SQLException { return open().prepareStatement(sql, type, concurrency, holdability); }
    @Override public PreparedStatement prepareStatement(String sql, int autoGeneratedKeys) throws SQLException { return open().prepareStatement(sql, autoGeneratedKeys); }
    @Override public PreparedStatement prepareStatement(String sql, int[] columnIndexes) throws SQLException { return open().prepareStatement(sql, columnIndexes); }
    @Override public PreparedStatement prepareStatement(String sql, String[] columnNames) throws SQLException { return open().prepareStatement(sql, columnNames); }
    @Override public CallableStatement prepareCall(String sql) throws SQLException { return open().prepareCall(sql); }
    @Override public CallableStatement prepareCall(String sql, int type, int concurrency) throws SQLException { return open().prepareCall(sql, type, concurrency); }
    @Override public CallableStatement prepareCall(String sql, int type, int concurrency, int holdability) throws SQLException { return open().prepareCall(sql, type, concurrency, holdability); }
    @Override public String nativeSQL(String sql) throws SQLException { return open().nativeSQL(sql); }

    @Override public DatabaseMetaData getMetaData() throws SQLException { return open().getMetaData(); }
    @Override public void setReadOnly(boolean readOnly) throws SQLException { open().setReadOnly(readOnly); }
    @Override public boolean isReadOnly() throws SQLException { return open().isReadOnly(); }
    @Override public void setCatalog(String catalog) throws SQLException { open().setCatalog(catalog); }
    @Override public String getCatalog() throws SQLException { return open().getCatalog(); }
    @Override public void setSchema(String schema) throws SQLException { open().setSchema(schema); }
    @Override public String getSchema() throws SQLException { return open().getSchema(); }
    @Override public void setTransactionIsolation(int level) throws SQLException { open().setTransactionIsolation(level); }
    @Override public int getTransactionIsolation() throws SQLException { return open().getTransactionIsolation(); }
    @Override public SQLWarning getWarnings() throws SQLException { return open().getWarnings(); }
    @Override public void clearWarnings() throws SQLException { open().clearWarnings(); }
    @Override public Map<String, Class<?>> getTypeMap() throws SQLException { return open().getTypeMap(); }
    @Override public void setTypeMap(Map<String, Class<?>> map) throws SQLException { open().setTypeMap(map); }
    @Override public void setHoldability(int holdability) throws SQLException { open().setHoldability(holdability); }
    @Override public int getHoldability() throws SQLException { return open().getHoldability(); }
    @Override public Savepoint setSavepoint() throws SQLException { return open().setSavepoint(); }
    @Override public Savepoint setSavepoint(String name) throws SQLException { return open().setSavepoint(name); }
    @Override public void releaseSavepoint(Savepoint savepoint) throws SQLException { open().releaseSavepoint(savepoint); }

    @Override public Clob createClob() throws SQLException { return open().createClob(); }
    @Override public Blob createBlob() throws SQLException { return open().createBlob(); }
    @Override public NClob createNClob() throws SQLException { return open().createNClob(); }
    @Override public SQLXML createSQLXML() throws SQLException { return open().createSQLXML(); }
    @Override public Array createArrayOf(String typeName, Object[] elements) throws SQLException { return open().createArrayOf(typeName, elements); }
    @Override public Struct createStruct(String typeName, Object[] attributes) throws SQLException { return open().createStruct(typeName, attributes); }

    @Override public void setClientInfo(String name, String value) throws SQLClientInfoException { physical.setClientInfo(name, value); }
    @Override public void setClientInfo(Properties properties) throws SQLClientInfoException { physical.setClientInfo(properties); }
    @Override public String getClientInfo(String name) throws SQLException { return open().getClientInfo(name); }
    @Override public Properties getClientInfo() throws SQLException { return open().getClientInfo(); }

    @Override public void abort(Executor executor) { closed = true; }
    @Override public void setNetworkTimeout(Executor executor, int milliseconds) throws SQLException { open().setNetworkTimeout(executor, milliseconds); }
    @Override public int getNetworkTimeout() throws SQLException { return open().getNetworkTimeout(); }

    @Override public <T> T unwrap(Class<T> type) throws SQLException { return type.isInstance(this) ? type.cast(this) : open().unwrap(type); }
    @Override public boolean isWrapperFor(Class<?> type) throws SQLException { return type.isInstance(this) || open().isWrapperFor(type); }
}
