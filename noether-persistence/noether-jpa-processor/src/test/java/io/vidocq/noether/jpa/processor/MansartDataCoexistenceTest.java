package io.vidocq.noether.jpa.processor;

import static org.assertj.core.api.Assertions.assertThat;

import io.vidocq.mansart.data.processor.MansartProcessor;
import java.nio.file.Path;
import java.util.List;
import javax.annotation.processing.Processor;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/**
 * BUG-20261009-09: the ecosystem's Jakarta Data processor ({@code mansart-data-processor}) and Noether's processor in
 * one compilation, as a Vidocq application declares them. Since Vidocq/mansart#95, Mansart Data writes its Jakarta Data
 * metamodel {@code _Book} only; the JPA canonical metamodel {@code Book_} comes from Noether, with the plural attribute
 * a {@code ListAttribute} (§6.2.1.1). {@link MetamodelCoexistenceTest} covers a producer that does write {@code Book_}.
 */
class MansartDataCoexistenceTest {

    @Test
    void noetherWritesTheCanonicalMetamodelAndMansartDataItsOwnInEitherOrder(@TempDir Path out) {
        for (boolean mansartFirst : List.of(true, false)) {
            Processor mansart = new MansartProcessor();
            Processor jpa = new NoetherJpaProcessor();
            var compilation = Compilation.withProcessors(out.resolve(mansartFirst ? "mansart-first" : "noether-first"),
                mansartFirst ? List.of(mansart, jpa) : List.of(jpa, mansart), Compilation.FIXTURES.resolve("datacoexist"));

            assertThat(compilation.success()).as("%s", compilation.diagnostics()).isTrue();
            assertThat(compilation.source("datacoexist/Book_.java")).as("Book_, Mansart first: %s", mansartFirst)
                .contains("// Generated by noether-jpa-processor")
                .contains("jakarta.persistence.metamodel.ListAttribute<datacoexist.Book, java.lang.String> tags;");
            assertThat(compilation.source("datacoexist/_Book.java")).as("_Book, Mansart first: %s", mansartFirst)
                .contains("@Generated(\"io.vidocq.mansart.data.processor.MansartProcessor\")");
        }
    }
}
