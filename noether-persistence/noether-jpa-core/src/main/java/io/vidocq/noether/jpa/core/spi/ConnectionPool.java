package io.vidocq.noether.jpa.core.spi;

import java.sql.Connection;
import java.sql.SQLException;

/** The connection pool of one persistence unit, opened by a {@link ConnectionPoolFactory}. It is thread-safe. */
public interface ConnectionPool extends AutoCloseable {

    /** A connection of the pool; closing it gives it back to the pool. */
    Connection getConnection() throws SQLException;

    /** Closes the pool and its connections; {@link #getConnection()} fails afterwards. */
    @Override
    void close();
}
