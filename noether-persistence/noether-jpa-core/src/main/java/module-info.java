/**
 * The Noether Jakarta Persistence 3.2 provider. It is published through {@link java.util.ServiceLoader}. Applications
 * only see the {@code jakarta.persistence} API, plus, when they compile with {@code noether-jpa-processor}, the SPI that
 * the generated accesses implement ({@code io.vidocq.noether.jpa.core.spi}); no {@code requires} needs to be
 * transitive. Nothing is opened: the entity packages are reached either through the accesses an application provides,
 * or, for classes compiled without the processor, because the application opens their packages to this module.
 */
// "module": the qualified exports name io.vidocq.noether.jpa.processor, built after this module
@SuppressWarnings("module")
module io.vidocq.noether.jpa.core {
    requires jakarta.persistence;
    requires static jakarta.validation;
    requires java.sql;
    requires java.xml;
    requires io.vidocq.noether.jpa.dialect.spi;
    requires io.vidocq.mansart.pool.core;

    // the SPI that the accesses generated by noether-jpa-processor implement and are handed over with
    exports io.vidocq.noether.jpa.core.spi;
    uses io.vidocq.noether.jpa.core.spi.ManagedAccessProvider;
    uses io.vidocq.noether.jpa.dialect.DialectFactory;
    uses jakarta.validation.spi.ValidationProvider;

    // the processor plans the generated accesses with the same code as the bootstrap (AccessPlanner)
    exports io.vidocq.noether.jpa.core.model to io.vidocq.noether.jpa.processor;
    exports io.vidocq.noether.jpa.core.model.source to io.vidocq.noether.jpa.processor;
    exports io.vidocq.noether.jpa.core.model.build to io.vidocq.noether.jpa.processor;

    provides jakarta.persistence.spi.PersistenceProvider
        with io.vidocq.noether.jpa.core.NoetherPersistenceProvider;
}
